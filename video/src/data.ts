/** Linear interpolation of a yearly series at a fractional year. */
export const valueAt = (series: number[], year: number) => {
  const i = Math.max(0, Math.min(series.length - 1, year - YEARS[0]));
  const lo = Math.floor(i);
  const hi = Math.min(series.length - 1, lo + 1);
  return series[lo] + (series[hi] - series[lo]) * (i - lo);
};
